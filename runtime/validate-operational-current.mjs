#!/usr/bin/env node
import fs from 'node:fs';
const p=process.argv[2]||'reference-systems/palestinian-edu-math-v1/operational/current.json';
const o=JSON.parse(fs.readFileSync(p,'utf8')); const f=[];
const m=o.metrics||{}, b=o.head_baseline_minimums||{}, r=o.router_runtime||{}, l=o.latest_product_instance||{};
if(o.operational_state_id!=='OMEGA_PAL_EDU_PRODUCTION_OPERATIONAL_CURRENT')f.push('STATE_ID');
if(o.result!=='PASS_WITHIN_BOUNDED_HOST_OPERATIONAL_SCOPE')f.push('STATE_RESULT');
if(o.reference_system?.id!=='OMEGA_PAL_EDU_PRODUCTION_REFERENCE_SYSTEM'||o.reference_system?.version!=='1.0.0')f.push('REF_ID_VERSION');
if(o.reference_system?.scope_id!=='PAL_G1_ADDITION_WITHIN_10_RESULT_UNKNOWN_EQUATION_CARD_PDF_HOST_ONLY')f.push('SCOPE');
if(o.reference_system?.head_package_sha256!=='0e248c5f39df4b406390ebb8186c1aeaec9f07f755941d34b2dacc57a1b0feaf')f.push('HEAD_SHA');
if(o.effective_autorecover?.head!=='OMEGA_AUTORECOVER_AUTHORITY_MANIFEST_v4_3')f.push('AUTORECOVER');
if(o.effective_autorecover?.sha256!=='b16530dfcab17b2e678079287463528740770845eb6f0161df43de2e242c84fd')f.push('AUTORECOVER_SHA');
if(o.effective_autorecover?.fallback!=='OMEGA_AUTORECOVER_AUTHORITY_MANIFEST_v4_2')f.push('FALLBACK');
if(r.id!=='OMEGA_PRODUCTION_ROUTER_v1'||r.qualification!=='PASS_13_OF_13')f.push('ROUTER');
if(r.source_sha256!=='18f75ca1e78303011c2af8c065b61bb275831fb9095cfc02d144d706d38fcc8b')f.push('ROUTER_SHA');
if(!Number.isInteger(m.runs_total)||m.runs_total<(b.runs_total||0))f.push('RUNS_MONOTONIC');
if(m.released+m.no_go!==m.runs_total)f.push('RUN_ACCOUNTING');
if(m.released<(b.released||0)||m.no_go<(b.no_go||0))f.push('RUN_CLASS_MONOTONIC');
if(m.valid_negative_fault_tests_total<(b.valid_negative_fault_tests_total||0))f.push('FAULT_COVERAGE_MONOTONIC');
if(m.valid_negative_fault_tests_detected!==m.valid_negative_fault_tests_total)f.push('FAULT_DETECTION_NOT_100_PERCENT');
if(m.valid_negative_fault_test_escapes!==0)f.push('FAULT_ESCAPE_NONZERO');
if(m.known_p0_escape_at_release_observed!==0)f.push('P0_ESCAPE_NONZERO');
if(m.field_escape_rate!=='UNKNOWN_NOT_MEASURED')f.push('FIELD_RATE_CLAIM');
if(m.aviation_nuclear_equivalent_failure_probability!=='NOT_ESTABLISHED')f.push('AVIATION_NUCLEAR_PROBABILITY_CLAIM');
if(l.release_decision!=='RELEASE'||l.student_eye!=='PASS'||l.negative_tests!=='4/4')f.push('LATEST_INSTANCE');
if(!(Array.isArray(o.limitations)&&o.limitations.includes('HOST_ONLY')&&o.limitations.includes('NO_AVIATION_NUCLEAR_EQUIVALENCE_CLAIM')&&o.limitations.includes('BOUNDED_SCOPE_ONLY')))f.push('LIMITATION_GUARDS');
if(!String(o.operational_law||'').includes('PASS is never inherited'))f.push('PASS_INHERITANCE_GUARD');
const result=f.length?'FAIL':'PASS';
console.log(JSON.stringify({validator_id:'OMEGA_OPERATIONAL_CURRENT_VALIDATOR_v1',result,failures:f,metrics:m},null,2));
process.exit(f.length?1:0);
