#!/usr/bin/env node
import fs from 'node:fs';
import crypto from 'node:crypto';
const read=p=>fs.readFileSync(p);
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const sha=p=>crypto.createHash('sha256').update(read(p)).digest('hex');
const M='sustainability/manifest.json';
const S=json(M), C=json('recovery/current.json'), H=json('recovery/head-v4.3.json'), F=json('recovery/fallback-v4.2.json');
const SC=json('sustainability/current.json'), PC=json('sustainability/provider-closure-v1.json');
const P=json('reference-systems/palestinian-edu-math-v1/manifest.json');
const O=json('reference-systems/palestinian-edu-math-v1/operational/current.json');
const failures=[];
const required=S.authoritative_storage.github.required||[];
for(const p of required) if(!fs.existsSync(p)) failures.push('MISSING:'+p);
for(const p of ['sustainability/current.json','sustainability/provider-closure-v1.json']) if(!fs.existsSync(p)) failures.push('MISSING:'+p);
if(S.sustainability_id!=='OMEGA_SUSTAINABILITY_MANIFEST_v1') failures.push('SUSTAINABILITY_ID');
if(C.effective_head!==S.protected_heads.autorecover_head) failures.push('CURRENT_HEAD');
if(C.effective_head_sha256!==S.protected_heads.autorecover_sha256) failures.push('CURRENT_HEAD_SHA_POINTER');
if(C.fallback_head!==S.protected_heads.fallback_head) failures.push('FALLBACK_HEAD');
if(C.fallback_sha256!==S.protected_heads.fallback_sha256) failures.push('FALLBACK_SHA_POINTER');
if(H.manifest_id!==S.protected_heads.autorecover_head) failures.push('MIRRORED_HEAD_ID');
if(sha('recovery/head-v4.3.json')!==S.protected_heads.autorecover_sha256) failures.push('MIRRORED_HEAD_SHA');
if(F.manifest_id!==S.protected_heads.fallback_head) failures.push('MIRRORED_FALLBACK_ID');
if(sha('recovery/fallback-v4.2.json')!==S.protected_heads.fallback_sha256) failures.push('MIRRORED_FALLBACK_SHA');
if(SC.pointer_id!=='OMEGA_SUSTAINABILITY_CURRENT'||SC.status!=='PASS_PROVIDER_VERIFIED') failures.push('SUSTAINABILITY_CURRENT_STATUS');
if(SC.sustainability_manifest!==S.sustainability_id) failures.push('SUSTAINABILITY_CURRENT_MANIFEST');
if(SC.autorecover_head!==S.protected_heads.autorecover_head||SC.autorecover_sha256!==S.protected_heads.autorecover_sha256) failures.push('SUSTAINABILITY_CURRENT_HEAD');
if(SC.fallback_head!==S.protected_heads.fallback_head||SC.fallback_sha256!==S.protected_heads.fallback_sha256) failures.push('SUSTAINABILITY_CURRENT_FALLBACK');
if(SC.production_sha256!==S.protected_heads.production_sha256) failures.push('SUSTAINABILITY_CURRENT_PRODUCTION');
if(SC.pass_inheritance!=='FORBIDDEN') failures.push('SUSTAINABILITY_CURRENT_PASS_INHERITANCE');
if(SC.provider_closure?.conclusion!=='success') failures.push('SUSTAINABILITY_PROVIDER_CLOSURE');
if(PC.evidence_id!=='OMEGA_SUSTAINABILITY_PROVIDER_CLOSURE_EVIDENCE_v1'||PC.result!=='PASS_PROVIDER_VERIFIED') failures.push('PROVIDER_CLOSURE_EVIDENCE');
if(PC.provider_verification?.run_id!==SC.provider_closure?.run_id||PC.provider_verification?.job_id!==SC.provider_closure?.job_id) failures.push('PROVIDER_CLOSURE_IDENTITY');
const prodId=P.production_head_id??P.reference_system_id;
const prodSha=P.package?.sha256??P.package_sha256;
if(prodId!=='OMEGA_PAL_EDU_PRODUCTION_REFERENCE_SYSTEM'||P.version!=='1.0.0') failures.push('PROD_ID_VERSION');
if(P.scope_id!==S.protected_heads.production_scope) failures.push('PROD_SCOPE');
if(prodSha!==S.protected_heads.production_sha256) failures.push('PROD_SHA');
if(O.result!=='PASS_WITHIN_BOUNDED_HOST_OPERATIONAL_SCOPE') failures.push('OPERATIONAL_STATE');
if(O.reference_system?.head_package_sha256!==S.protected_heads.production_sha256) failures.push('OPERATIONAL_PROD_SHA');
if(O.metrics?.valid_negative_fault_test_escapes!==0) failures.push('FAULT_ESCAPE_NONZERO');
if(O.metrics?.known_p0_escape_at_release_observed!==0) failures.push('P0_ESCAPE_NONZERO');
if(!String(O.operational_law||'').includes('PASS is never inherited')) failures.push('PASS_INHERITANCE_GUARD');
const wf=fs.readFileSync('.github/workflows/omega-dna.yml','utf8');
if(!wf.includes("cron: '17 3 * * *'")) failures.push('DAILY_CI_MISSING');
if(!wf.includes('Verify Omega sustainability and mirrored recovery heads')) failures.push('SUSTAINABILITY_GATE_NOT_WIRED');
if(!wf.includes('Execute Omega disaster-recovery drill')) failures.push('DR_DRILL_NOT_WIRED');
const forbidden=JSON.stringify(S.secret_and_key_policy);
if(/PRIVATE KEY-----|BEGIN OPENSSH PRIVATE KEY|seed_phrase|mnemonic/i.test(forbidden)) failures.push('SECRET_MATERIAL_IN_POLICY');
const result=failures.length?'FAIL':'PASS';
console.log(JSON.stringify({validator_id:'OMEGA_SUSTAINABILITY_VALIDATOR_v1_1',result,failures,head_sha:sha('recovery/head-v4.3.json'),fallback_sha:sha('recovery/fallback-v4.2.json'),provider_run:SC.provider_closure?.run_id,operational_runs:O.metrics?.runs_total},null,2));
process.exit(failures.length?1:0);
